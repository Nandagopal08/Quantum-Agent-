import { Bar, BarChart, CartesianGrid, Legend, Tooltip, XAxis, YAxis } from "recharts";
import { Download } from "lucide-react";
import { api } from "../services/api";
import { useApi } from "../hooks/useApi";
import { Button, Card, Empty, ErrorBox, Loading, Notice, PageHeader, Table, fmt } from "../components/ui";
import { ChartBox, PALETTE, tooltipStyle } from "../components/charts";

const download = (name, data) => {
  const url = URL.createObjectURL(new Blob([JSON.stringify(data, null, 2)], { type: "application/json" }));
  const a = document.createElement("a"); a.href = url; a.download = `${name}.json`; a.click(); URL.revokeObjectURL(url);
};

export default function ResearchEvaluation() {
  const comps = useApi(api.comparisons, []);
  const opt = useApi(api.optimizationResults, []);
  if (comps.loading || comps.error) {
    return (<><PageHeader title="Research Evaluation" />{comps.loading ? <Loading /> : <ErrorBox error={comps.error} code={comps.code} onRetry={comps.reload} />}</>);
  }
  const all = comps.data || [];
  const ruls = all.filter((c) => c.name.startsWith("rul_") && c.name.endsWith("_comparison"));
  const ims = all.find((c) => c.name === "ims_anomaly_comparison");
  const quantum = all.filter((c) => c.name.startsWith("quantum_vs_classical_")).map((c) => c.data);
  const stamp = (t) => new Date(t * 1000).toLocaleString();
  return (
    <>
      <PageHeader title="Research Evaluation" description="Comparison tables generated by actual training and evaluation runs, with the time each report was produced. Nothing on this page is entered by hand."
        actions={<Button variant="secondary" icon={Download} onClick={() => download("qadt_research_results", { comparisons: all, optimization: opt.data })}>Export all (JSON)</Button>} />
      {ruls.map((c) => {
        const rows = [...c.data.rows].sort((a, b) => a.rmse - b.rmse);
        return (
          <Card key={c.name} className="mb-4" title={`RUL prediction — C-MAPSS ${c.data.subset}`} subtitle={`Official test set (last cycle of each engine, RUL capped at 125) · report ${stamp(c.saved_at)}`}>
            <div className="grid gap-4 xl:grid-cols-3">
              <div className="min-w-0 xl:col-span-2"><Table rows={rows} rowKey={(r) => r.model} columns={[
                { key: "model", label: "Model" }, { key: "rmse", label: "RMSE", align: "right", render: (r) => fmt.n(r.rmse, 2) },
                { key: "mae", label: "MAE", align: "right", render: (r) => fmt.n(r.mae, 2) }, { key: "r2", label: "R²", align: "right", render: (r) => fmt.n(r.r2, 3) },
                { key: "nasa_score", label: "NASA score", align: "right", render: (r) => fmt.int(r.nasa_score) },
                { key: "pof_roc_auc", label: "PoF ROC-AUC", align: "right", render: (r) => fmt.n(r.pof_roc_auc, 3) },
                { key: "interval_coverage_90", label: "90% PI coverage", align: "right", render: (r) => fmt.pct(r.interval_coverage_90, 0) },
                { key: "train_seconds", label: "Train time", align: "right", render: (r) => `${fmt.n(r.train_seconds, 0)} s` }]} /></div>
              <ChartBox height={260}>
                <BarChart data={rows}><CartesianGrid strokeDasharray="3 3" vertical={false} /><XAxis dataKey="model" tick={{ fontSize: 10 }} interval={0} angle={-25} textAnchor="end" height={50} />
                  <YAxis /><Tooltip {...tooltipStyle} /><Legend /><Bar dataKey="rmse" name="RMSE" fill={PALETTE[0]} /><Bar dataKey="mae" name="MAE" fill={PALETTE[1]} /></BarChart>
              </ChartBox>
            </div>
          </Card>
        );
      })}
      {ims ? (
        <Card className="mb-4" title="Bearing anomaly detection — NASA IMS" subtitle={`${ims.data.labelling} · report ${stamp(ims.saved_at)}`}>
          <Table rows={ims.data.rows} rowKey={(r) => r.test + r.model} maxHeight={420} columns={[
            { key: "test", label: "Test" }, { key: "model", label: "Model" },
            { key: "roc_auc", label: "ROC-AUC", align: "right", render: (r) => fmt.n(r.roc_auc, 3) },
            { key: "precision", label: "Precision", align: "right", render: (r) => fmt.n(r.precision, 3) },
            { key: "recall", label: "Recall", align: "right", render: (r) => fmt.n(r.recall, 3) }, { key: "f1", label: "F1", align: "right", render: (r) => fmt.n(r.f1, 3) },
            { key: "false_alarm_rate", label: "False alarms", align: "right", render: (r) => fmt.pct(r.false_alarm_rate) },
            { key: "lead", label: "Detection lead time", render: (r) => Object.entries(r.lead_time_hours).map(([b, h]) => `b${b}: ${h} h`).join(" · ") }]} />
          <div className="mt-2 text-xs text-slate-500">The supervised model is trained on the other two tests and evaluated on the listed one (cross-test generalisation).</div>
        </Card>
      ) : <Empty>No IMS comparison report yet (run scripts/train_all_anomaly.py).</Empty>}
      <Card className="mb-4" title="Quantum vs classical" subtitle="Each row is one recorded simulator experiment against classical models on identical PCA features">
        <Table rows={quantum} rowKey={(r) => r.run} empty="No quantum experiments yet" columns={[
          { key: "run", label: "Run" }, { key: "task", label: "Task" },
          { key: "q", label: "Quantum", align: "right", render: (r) => `${r.comparison.metric} ${fmt.n(r.comparison.quantum, 3)}` },
          { key: "c", label: "Best classical", align: "right", render: (r) => `${r.comparison.best_classical_model} ${fmt.n(r.comparison.best_classical, 3)}` },
          { key: "depth", label: "Depth / gates", align: "right", render: (r) => `${r.quantum.circuit_depth} / ${r.quantum.gate_count}` },
          { key: "time", label: "Train time", align: "right", render: (r) => `${fmt.n(r.quantum.train_seconds, 1)} s` }]} />
        <div className="mt-2"><Notice>{quantum[0]?.comparison.note || "Quantum results are simulator measurements; no quantum advantage is claimed."}</Notice></div>
      </Card>
      <Card title="QAOA vs classical scheduling" subtitle="Each optimisation run's measured cost and gap to the exact MILP optimum">
        <Table rows={(opt.data || []).map((r) => ({ id: r.generated_at, n: r.problem.assets.length, q: r.qubo_variables, ...Object.fromEntries(r.results.map((x) => [x.solver, x])) }))}
          rowKey={(r) => r.id} empty="No optimisation runs yet" columns={[
            { key: "id", label: "Run" }, { key: "n", label: "Assets", align: "right" }, { key: "q", label: "QUBO vars", align: "right" },
            { key: "milp", label: "MILP cost", align: "right", render: (r) => fmt.int(r.milp_highs?.total_expected_cost) },
            { key: "greedy", label: "Greedy gap", align: "right", render: (r) => `${fmt.n(r.greedy?.gap_percent, 2)}%` },
            { key: "sa", label: "Annealing gap", align: "right", render: (r) => `${fmt.n(r.simulated_annealing?.gap_percent, 2)}%` },
            { key: "qaoa", label: "QAOA gap", align: "right", render: (r) => (r.qaoa?.error ? "n/a" : `${fmt.n(r.qaoa?.gap_percent, 2)}%`) },
            { key: "qt", label: "QAOA time", align: "right", render: (r) => (r.qaoa?.runtime_seconds ? `${fmt.n(r.qaoa.runtime_seconds, 1)} s` : "—") }]} />
      </Card>
    </>
  );
}
